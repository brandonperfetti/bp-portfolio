// Prism after 1.27 added a bash `parameter` token (alias `variable`) for flags such
// as `-euo`, and the theme colours `.language-bash .token.variable` red, so
// every flag in a shell block would change colour. Remove it from the grammar
// and from the copy inside double-quoted strings' command substitutions, so a
// bash block renders the spans refractor 3.6.0 rendered.
const bashGrammar = refractor.languages.bash as
  Record<string, unknown> | undefined
if (bashGrammar) {
  delete bashGrammar.parameter
  const strings = Array.isArray(bashGrammar.string)
    ? bashGrammar.string
    : [bashGrammar.string]
  for (const string of strings as Array<{ inside?: { variable?: unknown } }>) {
    const variable = string?.inside?.variable
    if (!Array.isArray(variable)) continue
    for (const entry of variable as Array<{ inside?: Record<string, unknown> }>)
      delete entry?.inside?.parameter
  }
}

